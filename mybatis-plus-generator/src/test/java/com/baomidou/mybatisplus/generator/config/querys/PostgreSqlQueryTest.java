package com.baomidou.mybatisplus.generator.config.querys;

import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

@Tag("external-db")
@EnabledIfEnvironmentVariable(named = "MP_POSTGRES_TEST_URL", matches = ".+")
class PostgreSqlQueryTest {

    @Test
    void distinguishesIdentityAndSerialFromAssignedKeys() throws SQLException {
        try (Connection connection = DriverManager.getConnection(System.getenv("MP_POSTGRES_TEST_URL"));
                Statement statement = connection.createStatement()) {
            statement.execute(
                    "CREATE TEMP TABLE generated_keys (always_id bigint GENERATED ALWAYS AS IDENTITY,"
                            + " default_id bigint GENERATED BY DEFAULT AS IDENTITY, serial_id bigserial, manual_id bigint)");
            String schema;
            try (ResultSet rows = statement.executeQuery("SELECT pg_my_temp_schema()::regnamespace::text")) {
                rows.next();
                schema = rows.getString(1);
            }
            PostgreSqlQuery query = new PostgreSqlQuery();
            String sql = String
                    .format(query.tableFieldsSql(), "generated_keys", "generated_keys", "generated_keys", schema);
            List<String> generated = new ArrayList<>();
            try (ResultSet rows = statement.executeQuery(sql)) {
                while (rows.next()) {
                    if (query.isKeyIdentity(rows)) {
                        generated.add(rows.getString(query.fieldName()));
                    }
                }
            }
            assertThat(generated).containsExactly("always_id", "default_id", "serial_id");
        }
    }

    @Test
    void listsOnlyTheRequestedSchemasTableAfterARewrite() throws SQLException {
        try (Connection first = DriverManager.getConnection(System.getenv("MP_POSTGRES_TEST_URL"));
                Connection second = DriverManager.getConnection(System.getenv("MP_POSTGRES_TEST_URL"));
                Statement statement = first.createStatement();
                Statement other = second.createStatement()) {
            statement.execute("CREATE TEMP TABLE catalog_item (id int)");
            other.execute("CREATE TEMP TABLE catalog_item (id int)");
            statement.execute("COMMENT ON TABLE catalog_item IS 'first schema'");
            other.execute("COMMENT ON TABLE catalog_item IS 'other schema'");
            statement.execute("TRUNCATE catalog_item");
            String schema;
            try (ResultSet rows = statement.executeQuery("SELECT pg_my_temp_schema()::regnamespace::text")) {
                rows.next();
                schema = rows.getString(1);
            }
            PostgreSqlQuery query = new PostgreSqlQuery();
            String sql = String.format(query.tablesSql(), schema) + " AND tablename IN ('catalog_item')";
            try (ResultSet rows = statement.executeQuery(sql)) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getString(query.tableName())).isEqualTo("catalog_item");
                assertThat(rows.getString(query.tableComment())).isEqualTo("first schema");
                assertThat(rows.next()).isFalse();
            }
        }
    }

    @Test
    void onlyMarksPrimaryKeyColumns() throws SQLException {
        try (Connection connection = DriverManager.getConnection(System.getenv("MP_POSTGRES_TEST_URL"));
                Statement statement = connection.createStatement()) {
            statement.execute(
                    "CREATE TEMP TABLE indexed_item (tag text, code int, tenant int, id int, PRIMARY KEY (tenant, id) INCLUDE (tag))");
            statement.execute("CREATE INDEX ON indexed_item (tag)");
            statement.execute("CREATE UNIQUE INDEX ON indexed_item (code)");
            statement.execute("CREATE INDEX ON indexed_item (code, tag)");

            String schema;
            try (ResultSet rows = statement.executeQuery("SELECT pg_my_temp_schema()::regnamespace::text")) {
                rows.next();
                schema = rows.getString(1);
            }
            PostgreSqlQuery query = new PostgreSqlQuery();
            String sql = String.format(query.tableFieldsSql(), "indexed_item", "indexed_item", "indexed_item", schema);
            List<String> fields = new ArrayList<>();
            List<String> keys = new ArrayList<>();
            try (ResultSet rows = statement.executeQuery(sql)) {
                while (rows.next()) {
                    String field = rows.getString(query.fieldName());
                    fields.add(field);
                    if ("PRI".equals(rows.getString(query.fieldKey()))) {
                        keys.add(field);
                    }
                }
            }
            assertThat(fields).containsExactly("tag", "code", "tenant", "id");
            assertThat(keys).containsExactly("tenant", "id");
        }
    }
}
